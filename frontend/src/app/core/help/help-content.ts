export function journeyIndex(status: string | null | undefined): number {
  switch (status) {
    case 'SUBMITTED':
      return 0;
    case 'AI_PROCESSING':
    case 'REEVALUATION_REQUESTED':
      return 1;
    case 'AI_EVALUATED':
    case 'IN_REVIEW':
      return 2;
    case 'OFFER_SENT':
      return 3;
    case 'ACCEPTED':
      return 4;
    default:
      return -1;
  }
}

